"""
⚠️  MOCK PIPELINE — FOR DEVELOPMENT ONLY ⚠️

This module returns hardcoded, fictional evidence and verdicts so the UI
can be built and tested without a real retrieval or reasoning system.

CONTRACT:
  - Every object produced here has  is_mock=True
  - The returned Investigation has  is_mock=True  and a  mock_disclaimer
  - The UI MUST display the disclaimer prominently
  - These results MUST NOT be presented as real fact-checks

To plug in the real pipeline later, implement the same function signature
in a new module and update the router import.  Nothing else changes.
"""

import logging
import uuid

from backend.schemas.claim import AtomicClaim, ClaimSubmission
from backend.schemas.evidence import EvidencePassage
from backend.schemas.investigation import Investigation, InvestigationStatus
from backend.schemas.verdict import Verdict, VerdictLabel

logger = logging.getLogger(__name__)

MOCK_DISCLAIMER = (
    "⚠️ MOCK DATA — These results were generated by a placeholder pipeline "
    "and do NOT reflect real fact-checking. Do not use them to form opinions "
    "about the claim."
)

# ---------------------------------------------------------------------------
# Hardcoded mock passages — fictional, clearly labelled
# ---------------------------------------------------------------------------

_MOCK_PASSAGES = [
    {
        "text": (
            "[MOCK] Source Alpha states: 'According to our records this claim "
            "has been disputed by multiple independent researchers.'"
        ),
        "source_title": "Mock Source Alpha",
        "source_url": None,
        "relevance_score": 0.82,
    },
    {
        "text": (
            "[MOCK] Source Beta states: 'Some studies appear to support aspects "
            "of this claim, though the evidence is mixed and inconclusive.'"
        ),
        "source_title": "Mock Source Beta",
        "source_url": None,
        "relevance_score": 0.74,
    },
    {
        "text": (
            "[MOCK] Source Gamma states: 'No peer-reviewed literature was found "
            "that directly addresses this specific claim.'"
        ),
        "source_title": "Mock Source Gamma",
        "source_url": None,
        "relevance_score": 0.61,
    },
]


def run_mock_pipeline(submission: ClaimSubmission) -> Investigation:
    """
    Build and return a fully-populated mock Investigation.

    Parameters
    ----------
    submission : ClaimSubmission
        The validated claim submitted by the user.

    Returns
    -------
    Investigation
        A mock investigation with is_mock=True and a prominent disclaimer.
    """
    logger.info("[MOCK PIPELINE] Processing claim: %.80s…", submission.text)

    investigation_id = str(uuid.uuid4())
    claim_id = str(uuid.uuid4())

    # --- Atomic claim (1:1 with submission in milestone 1) ----------------
    atomic_claim = AtomicClaim(
        id=claim_id,
        text=submission.text,
        source_submission_id=investigation_id,
    )

    # --- Evidence passages -------------------------------------------------
    passages = [
        EvidencePassage(
            id=str(uuid.uuid4()),
            atomic_claim_id=claim_id,
            text=p["text"],
            source_title=p["source_title"],
            source_url=p["source_url"],
            relevance_score=p["relevance_score"],
            is_mock=True,
        )
        for p in _MOCK_PASSAGES
    ]

    # --- Verdict -----------------------------------------------------------
    # Always UNVERIFIED in mock mode — the least misleading label.
    verdict = Verdict(
        atomic_claim_id=claim_id,
        label=VerdictLabel.UNVERIFIED,
        confidence=None,
        explanation=(
            "[MOCK] No real analysis was performed. The pipeline returned "
            "placeholder evidence only. This verdict carries no factual weight."
        ),
        is_mock=True,
    )

    investigation = Investigation(
        id=investigation_id,
        submission=submission,
        atomic_claims=[atomic_claim],
        evidence_passages=passages,
        verdicts=[verdict],
        status=InvestigationStatus.COMPLETE,
        is_mock=True,
        mock_disclaimer=MOCK_DISCLAIMER,
    )

    logger.info("[MOCK PIPELINE] Returning mock investigation %s", investigation_id)
    return investigation
