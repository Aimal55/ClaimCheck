"""
Evidence passage schema.

An EvidencePassage represents a retrieved chunk of text that is relevant
to a specific AtomicClaim.  In milestone 1 these are mock objects; in later
milestones they will come from a real retrieval step.
"""

from pydantic import BaseModel, ConfigDict, Field, HttpUrl


class EvidencePassage(BaseModel):
    """A snippet of text retrieved as evidence for or against a claim."""

    model_config = ConfigDict(frozen=True)

    id: str = Field(..., description="Unique identifier for this passage.")
    atomic_claim_id: str = Field(
        ..., description="The AtomicClaim this passage relates to."
    )
    text: str = Field(..., description="The retrieved text passage.")
    source_url: str | None = Field(
        default=None,
        description="URL of the source document, if available.",
    )
    source_title: str | None = Field(
        default=None, description="Human-readable title of the source."
    )
    relevance_score: float | None = Field(
        default=None,
        ge=0.0,
        le=1.0,
        description="Similarity score from retrieval (0–1). None when not computed.",
    )
    chunk_id: str | None = Field(default=None, description="Source chunk identifier.")
    stance: str | None = Field(default=None, description="SUPPORTS, REFUTES, or NEUTRAL.")
    rerank_score: float | None = Field(default=None, ge=0.0, le=1.0)
    is_mock: bool = Field(
        default=False,
        description="True when this passage was generated by the mock pipeline.",
    )
